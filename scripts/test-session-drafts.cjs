const assert = require('node:assert/strict');
const fs = require('node:fs');
const { JSDOM } = require('jsdom');
const dom = new JSDOM('<input id="note"><input id="secret" type="text" autocomplete="current-password"><input id="code" autocomplete="one-time-code">', {url:'https://example.com/journal.html',runScripts:'outside-only'});
const w=dom.window;
w.eval(fs.readFileSync('assets/js/session-manager.js','utf8').replace(/import\s+[\s\S]*?from\s+"[^"]+";/g,'').replace(/export /g,'').replace(/let currentAuth/g,'var currentAuth').replace(/let pageStateOwner/g,'var pageStateOwner'));
w.eval('currentAuth = {currentUser:{uid:"A"}}; pageStateOwner="A";');
w.document.getElementById('note').value='Alice draft';
w.document.getElementById('secret').value='do not persist';
w.document.getElementById('code').value='123456';
w.FynxSession.savePageState();
assert.deepEqual(JSON.parse(JSON.stringify(w.FynxSession.getPageState().values)),{note:'Alice draft'});
w.eval('currentAuth.currentUser = {uid:"B"};');
assert.equal(w.FynxSession.getPageState(),null);
w.FynxSession.savePageState();
w.eval('pageStateOwner="B";');
assert.equal(w.FynxSession.getPageState(),null);
w.document.getElementById('note').value='Bob draft';w.FynxSession.savePageState();
w.eval('currentAuth.currentUser={uid:"A"};pageStateOwner="A";');
w.FynxSession.restorePageState();assert.equal(w.document.getElementById('note').value,'Alice draft');
w.eval('pageStateOwner=null;');assert.equal(w.FynxSession.getPageState(),null);
w.close();console.log('Draft ownership isolation and password/code exclusion passed.');
